export type MsgKey = keyof Dict
const dicts: Record<Lang, Dict> = { en, hi }

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: MsgKey, vars?: Record<string, string | number>) => string }
const I18n = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en")
  useEffect(() => {
    try {
      const saved = localStorage.getItem("turn-lang")
      if (saved === "en" || saved === "hi") setLangState(saved)
    } catch {}
  }, [])
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem("turn-lang", l) } catch {}
  }, [])
  const t = useCallback((k: MsgKey, vars?: Record<string, string | number>) => {
    let s: string = dicts[lang][k] ?? en[k]
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v))
    return s
  }, [lang])
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <I18n.Provider value={value}>{children}</I18n.Provider>
}

export function useT() {
  const c = useContext(I18n)
  if (!c) throw new Error("I18nProvider missing")
  return c
}
